@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun DigitalTwinDashboardScreen(onBack: () -> Unit, viewModel: DigitalTwinDashboardViewModel = hiltViewModel()) {
    val uiState by viewModel.uiState.collectAsState()
    val dashboard = uiState.dashboard
    Scaffold(topBar = { TopAppBar(title = { Text("Digital Twin AI") }, navigationIcon = { IconButton(onClick = onBack) { Icon(Icons.AutoMirrored.Rounded.ArrowBack, contentDescription = "Back") } }) }) { padding ->
        Column(Modifier.fillMaxSize().padding(padding).verticalScroll(rememberScrollState()).padding(20.dp), verticalArrangement = Arrangement.spacedBy(16.dp)) {
            Button(onClick = viewModel::createTwin, enabled = !uiState.loading) { Icon(Icons.Rounded.ViewInAr, contentDescription = null); Text("Create Twin") }
            if (uiState.loading) CircularProgressIndicator()
            uiState.message?.let { Text(it, color = MaterialTheme.colorScheme.primary) }
            uiState.errorMessage?.let { Text(it, color = MaterialTheme.colorScheme.error) }
            Metric("Learning Progress", dashboard.learningProgress)
            Info("Active Twins", dashboard.activeTwins.ifEmpty { listOf("Digital twins appear here.") }.joinToString("\n"))
            Info("Simulation Status", dashboard.simulationStatus.ifEmpty { listOf("Simulation scenarios appear here.") }.joinToString("\n"))
            Info("Analysis Reports", dashboard.analysisReports.ifEmpty { listOf("Twin analysis appears here.") }.joinToString("\n"))
            Info("Experiment History", dashboard.experimentHistory.ifEmpty { listOf("Experiment history appears here.") }.joinToString("\n"))
            Info("Real-World Sync", dashboard.syncSummary.ifEmpty { listOf("Sensor and AR sync appears here.") }.joinToString("\n"))
            Info("Predictions", dashboard.predictions.ifEmpty { listOf("Prediction records appear here.") }.joinToString("\n"))
            Info("Learning Sessions", dashboard.learningSessions.ifEmpty { listOf("Learning tasks appear here.") }.joinToString("\n"))
            Info("Safety", dashboard.safetyStatus.ifBlank { "Safety status appears here." })
        }
    }
}

@Composable private fun Metric(title: String, value: Int) { Card(Modifier.fillMaxWidth(), shape = MaterialTheme.shapes.small) { Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) { Text(title, fontWeight = FontWeight.SemiBold); LinearProgressIndicator(progress = { value / 100f }, modifier = Modifier.fillMaxWidth()); Text("$value%", color = MaterialTheme.colorScheme.onSurfaceVariant) } } }
@Composable private fun Info(title: String, body: String) { Card(Modifier.fillMaxWidth(), shape = MaterialTheme.shapes.small) { Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) { Text(title, fontWeight = FontWeight.SemiBold); Text(body, color = MaterialTheme.colorScheme.onSurfaceVariant) } } }
